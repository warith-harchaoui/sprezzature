"""
Every brick's README opens on a drawing of how it works, and that drawing says
what the brick's own specification says.

The figures are generated by ``scripts/make_brick_diagram.py`` from a
specification each brick keeps at ``assets/how-it-works.yaml``. Two things can
go wrong quietly:

* somebody edits the specification and does not redraw, so the file that gets
  read on GitHub and on PyPI says the old thing while the repository says the
  new one;
* somebody adds a brick and the README has no figure, which nothing notices
  because a missing section looks like a section that was never wanted.

This repository is the only place that sees all eleven at once, so the guard
belongs here. ``scripts/fetch_siblings.sh`` brings the three asset files in on
CI; without them the whole module would skip, and a skip reads exactly like a
pass.

What is **not** checked is the layout: the box heights, the wrap points, where
the arrows land. Those come from a Roboto advance table, and a drift there
makes a figure uglier, not untrue. The text is what can lie.

Author
------
Warith HARCHAOUI <warithmetics@deraison.ai>
"""

from __future__ import annotations

import re
import sys
import xml.etree.ElementTree as ET
from pathlib import Path
from typing import Any, Dict, Iterator, List

import pytest
import yaml

REPO_ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(REPO_ROOT / "scripts"))

from skills_manifest import SHIPPED_SKILLS  # noqa: E402

#: The ten bricks and the hub. Not read from ``SKILLS.txt`` alone: that file
#: lists what gets released as a skill, and this repository's own README opens
#: on the same drawing.
DIAGRAMMED = (*SHIPPED_SKILLS, "sprezzature")

SVG_NS = "{http://www.w3.org/2000/svg}"

#: Per language: the document, the figure beside it, and the heading it is under.
LANGS = {
    "en": ("README.md", "how-it-works.svg"),
    "fr": ("LISEZMOI.md", "comment-ca-marche.svg"),
}

RAW = "https://raw.githubusercontent.com/warith-harchaoui/{brick}/main/assets/{name}"


def root_of(brick: str) -> Path:
    """Checkout directory for ``brick``. The hub is this repository itself."""
    return REPO_ROOT if brick == "sprezzature" else REPO_ROOT.parent / brick


def present(brick: str) -> bool:
    """Is this brick's checkout here, with its figure assets?"""
    return (root_of(brick) / "assets" / "how-it-works.yaml").is_file()


def spec_of(brick: str) -> Dict[str, Any]:
    """Parse one brick's figure specification."""
    return yaml.safe_load(
        (root_of(brick) / "assets" / "how-it-works.yaml").read_text(encoding="utf-8")
    )


def spec_strings(half: Dict[str, Any]) -> Iterator[str]:
    """Every string the renderer draws, for one language half.

    ``alt`` is excluded: it goes into ``<desc>``, not into a ``<text>``, and
    is checked separately.
    """
    yield half["title"]
    yield half["subtitle"]
    yield half["footer"]
    yield half["input"]["label"]
    if half["input"].get("note"):
        yield half["input"]["note"]
    for lane in half["lanes"]:
        yield lane["title"]
        for box in [*lane["steps"], lane["result"]]:
            yield box["label"]
            if box.get("note"):
                yield box["note"]
    if half.get("outcome"):
        yield half["outcome"]["label"]
        if half["outcome"].get("note"):
            yield half["outcome"]["note"]


def flat(text: str) -> str:
    """Collapse runs of whitespace, so a wrapped line matches its source."""
    return " ".join(text.split())


def drawn_text(svg: Path) -> str:
    """Every ``<text>`` in the figure, in document order, joined by spaces."""
    tree = ET.parse(svg)
    return flat(" ".join(el.text or "" for el in tree.getroot().iter(SVG_NS + "text")))


#: Collected at import, because pytest needs the parameter list before it can
#: run anything. A machine holding one clone parametrises over one brick and
#: says so through the last test in this file; a runner holds all eleven.
HERE: List[str] = [b for b in DIAGRAMMED if present(b)]


@pytest.mark.parametrize("brick", DIAGRAMMED)
def test_a_brick_carries_its_figure_specification(brick: str) -> None:
    """Every brick has an ``assets/how-it-works.yaml`` with both languages."""
    root = root_of(brick)
    if not root.is_dir():
        pytest.skip(f"{brick} is not checked out beside this repository")
    spec = root / "assets" / "how-it-works.yaml"
    assert spec.is_file(), (
        f"{brick} has no assets/how-it-works.yaml. Its README opens on a figure "
        "drawn from that file; without it there is nothing to redraw from. "
        "Copy a sibling's and rewrite it, then run "
        f"`python scripts/make_brick_diagram.py {brick}`."
    )
    parsed = yaml.safe_load(spec.read_text(encoding="utf-8"))
    assert parsed.get("package") == brick, f"{spec}: package name does not match the folder"
    for lang in LANGS:
        assert lang in parsed, f"{spec}: no '{lang}' half. The two languages stay in step."
        for key in ("title", "subtitle", "alt", "footer", "input", "lanes"):
            assert key in parsed[lang], f"{spec}: {lang} has no '{key}'"
        assert len(parsed[lang]["lanes"]) == 2, (
            f"{spec}: {lang} has {len(parsed[lang]['lanes'])} lanes. The figure is "
            "two lanes by design: what the brick makes, and what it audits."
        )


@pytest.mark.parametrize("brick", HERE)
@pytest.mark.parametrize("lang", sorted(LANGS))
def test_the_figure_says_what_the_specification_says(brick: str, lang: str) -> None:
    """Every string in the specification is drawn in the figure, word for word.

    This is the staleness guard. An edit to the YAML that was not followed by
    a redraw leaves the committed SVG saying the old thing, and the SVG is
    what a reader sees.
    """
    svg = root_of(brick) / "assets" / LANGS[lang][1]
    assert svg.is_file(), (
        f"{brick}: {svg.name} is missing. Run "
        f"`python scripts/make_brick_diagram.py {brick}`."
    )
    drawn = drawn_text(svg)
    for wanted in spec_strings(spec_of(brick)[lang]):
        assert flat(wanted) in drawn, (
            f"{brick}/{svg.name} does not carry {flat(wanted)[:70]!r}.\n"
            "The specification moved and the figure did not. Redraw with "
            f"`python scripts/make_brick_diagram.py {brick}`."
        )


@pytest.mark.parametrize("brick", HERE)
@pytest.mark.parametrize("lang", sorted(LANGS))
def test_the_figure_describes_itself(brick: str, lang: str) -> None:
    """A ``<title>`` and a ``<desc>`` carrying the specification's own alt text.

    A figure is the one thing on a README page a screen reader cannot guess
    at. This is the suite's own accessibility rule applied to its own files.
    """
    svg = root_of(brick) / "assets" / LANGS[lang][1]
    root = ET.parse(svg).getroot()
    assert root.get("role") == "img", f"{svg}: no role=\"img\" on the root element"
    title = root.find(SVG_NS + "title")
    desc = root.find(SVG_NS + "desc")
    assert title is not None and (title.text or "").strip(), f"{svg}: empty or missing <title>"
    assert desc is not None, f"{svg}: no <desc>"
    half = spec_of(brick)[lang]
    assert flat(desc.text or "") == flat(half["alt"]), (
        f"{svg}: <desc> is not the specification's alt text. Redraw."
    )
    labelled = root.get("aria-labelledby", "")
    assert title.get("id") in labelled and desc.get("id") in labelled, (
        f"{svg}: aria-labelledby does not name both the title and the description"
    )


@pytest.mark.parametrize("brick", HERE)
@pytest.mark.parametrize("lang", sorted(LANGS))
def test_the_figure_reads_in_the_dark(brick: str, lang: str) -> None:
    """An additive dark-mode block, and no embedded faces.

    Two separate traps. A figure with a white paper and no dark block is a
    white slab on a dark README. A figure with the Roboto faces embedded is
    438 KB of base64 per file, for typography the reader's own machine
    supplies well enough.
    """
    text = (root_of(brick) / "assets" / LANGS[lang][1]).read_text(encoding="utf-8")
    assert "@media (prefers-color-scheme: dark)" in text, (
        f"{brick}/{LANGS[lang][1]}: no dark-mode block. On a dark README this is a "
        "white rectangle."
    )
    assert "@font-face" not in text, (
        f"{brick}/{LANGS[lang][1]}: the faces are embedded. That is 438 KB of base64 "
        "per file; the font stack falls back to Helvetica and Arial on purpose."
    )


@pytest.mark.parametrize("brick", HERE)
@pytest.mark.parametrize("lang", sorted(LANGS))
def test_the_document_opens_on_the_figure(brick: str, lang: str) -> None:
    """The README points at the figure, by an absolute URL, with real alt text.

    Absolute because README.md is also the PyPI long description, where a
    relative image source is a broken image and nothing says why.
    """
    doc_name, svg_name = LANGS[lang]
    doc = root_of(brick) / doc_name
    text = doc.read_text(encoding="utf-8")
    url = RAW.format(brick=brick, name=svg_name)
    assert url in text, (
        f"{brick}/{doc_name} does not show {svg_name}. Expected an image whose "
        f"source is {url}"
    )
    found = re.search(r"!\[([^\]]*)\]\(" + re.escape(url) + r"\)", text)
    assert found, f"{brick}/{doc_name}: {svg_name} is linked but not shown as an image"
    alt = flat(found.group(1))
    assert flat(spec_of(brick)[lang]["alt"]) == alt, (
        f"{brick}/{doc_name}: the image's alt text is not the one the specification "
        "carries. The two have to say the same thing, because a reader gets one or "
        "the other and never both."
    )


def test_ci_fetches_the_assets_this_file_asks_for() -> None:
    """The three files this guard reads, and the fetch script's path list, are
    one question.

    ``scripts/fetch_siblings.sh`` brings a sibling in as a sparse checkout of
    named paths, and ``assets/`` was deliberately excluded from them: it is
    where the weight is, and nothing that looks across the bricks read it.
    That stopped being true the day the READMEs opened on a figure. Named
    here rather than in a comment there, because a comment is not a check.
    """
    fetch = REPO_ROOT / "scripts" / "fetch_siblings.sh"
    assert fetch.is_file(), fetch
    block = re.search(r"^PATHS=\((.*?)^\)", fetch.read_text(encoding="utf-8"), re.M | re.S)
    assert block, "fetch_siblings.sh no longer declares a PATHS array"
    fetched = set(re.findall(r"'/([^']+)'", block.group(1)))
    wanted = {"assets/how-it-works.yaml", *(f"assets/{n}" for _, n in LANGS.values())}
    missing = sorted(wanted - fetched)
    assert not missing, (
        f"this guard reads {missing} and fetch_siblings.sh does not bring them, "
        "so the file is red on CI and green on a machine holding real clones. "
        "Add the paths there."
    )


def test_this_run_saw_bricks_to_check() -> None:
    """A file that skipped everything reads exactly like a file that passed.

    Not a count of the eleven: that would measure which checkouts this machine
    happens to hold rather than whether the guard works.
    """
    assert HERE, (
        "no checkout carries assets/how-it-works.yaml, so every figure test in "
        "this file skipped. Run scripts/fetch_siblings.sh, which is what CI does."
    )
